/** شرح متحرك لرمز الجزري: شعار واحد يضوي حرف حرف (عربي ثم إنجليزي ثم الشكل الكامل)
 *  مع بطاقة شرح تتبدل لكل خطوة، وزر تقليب يدوي، وتبديل تلقائي كل 5 ثواني إذا ما
 *  ضغطت المستخدمة الزر بنفسها (والعداد يرجع يبدأ من جديد بعد كل ضغطة يدوية). */
export default function AboutSymbolExplainer({
  steps,
}: {
  steps: Record<StepKey, { title: string; desc: string }>;
}) {
  const [stepIndex, setStepIndex] = useState(0);
  const current = STEPS[stepIndex];

  const goNext = useCallback(() => {
    setStepIndex(i => (i + 1) % STEPS.length);
  }, []);

  useEffect(() => {
    const id = setInterval(goNext, AUTO_ADVANCE_MS);
    return () => clearInterval(id);
  }, [stepIndex, goNext]);

  return (
    <div className="mx-auto flex max-w-md flex-col items-center gap-8 text-center">
      <motion.div
        animate={{ y: [0, -8, 0] }}
        transition={{ duration: 3, repeat: Infinity, ease: 'easeInOut' }}
      >
        <SymbolMark group={current.group} className="h-32 w-auto sm:h-40" />
      </motion.div>

      <AnimatePresence mode="wait">
        <motion.div
          key={current.key}
          initial={{ opacity: 0, y: 12 }}
          animate={{ opacity: 1, y: 0 }}
          exit={{ opacity: 0, y: -12 }}
          transition={{ duration: 0.35, ease: 'easeOut' }}
          className="glass-card w-full rounded-3xl px-6 py-5"
        >
          <h3 className="text-lg font-semibold text-white">{steps[current.key].title}</h3>
          <p className="mt-2 text-sm leading-relaxed text-purple-200/75">{steps[current.key].desc}</p>
        </motion.div>
      </AnimatePresence>

      <div className="flex items-center gap-4">
        <div className="flex items-center gap-2">
          {STEPS.map((s, i) => (
            <span
              key={s.key}
              className={`h-1.5 rounded-full transition-all duration-300 ${
                i === stepIndex ? 'w-8 bg-purple-300' : 'w-2 bg-purple-300/30'
              }`}
            />
          ))}
        </div>

        <button
          type="button"
          onClick={goNext}
          aria-label="التالي"
          className="glass-pill flex h-11 w-11 items-center justify-center rounded-full text-purple-200 transition hover:scale-105 hover:text-white active:scale-95"
        >
          {/* السهم يشير باتجاه القراءة: يسار بالعربي، يمين بالإنجليزي */}
          <ArrowLeft size={18} className="rtl:block ltr:hidden" />
          <ArrowRight size={18} className="ltr:block rtl:hidden" />
        </button>
      </div>
    </div>
  );
}
